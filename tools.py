import math


def add(a, b):
    """Dodaje a i b."""
    return a + b


def subtract(a, b):
    """Odejmuje b od a."""
    return a - b


def multiply(a, b):
    """Mnoży a przez b."""
    return a * b


def divide(a, b):
    """Dzieli a przez b."""
    return a / b


def modulo(a, b):
    """Zwraca resztę z dzielenia a przez b."""
    return a % b


def power(a, b):
    """Podnosi a do potęgi b."""
    return a**b


def absolute_value(a):
    """Zwraca wartość bezwzględną a."""
    return abs(a)


def square_root(a):
    """Oblicza pierwiastek kwadratowy z a."""
    return math.sqrt(a)
